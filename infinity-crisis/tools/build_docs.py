"""Generate the derived deliverables from data/ and the screenplay.

    python3 tools/build_docs.py

Writes:
  docs/C_storyboard/README.md + S01..S11.md   shot-by-shot storyboard (all 13 fields, timecodes,
                                              continuity state of every character in shot)
  docs/D_continuity_sheet.md                  per-sequence continuity tables + event log
  docs/G_video_prompts/README.md + S01..S11.md  one self-contained prompt per shot
  output/edit/prompts.jsonl                   the same prompts, machine-readable
  output/edit/edl.csv                         edit decision list (source/record timecodes)
  output/edit/INFINITY_CRISIS.edl             CMX3600 EDL for conform (one event per shot)
  output/edit/runtime.md                      runtime table
"""
import csv
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common as C  # noqa: E402

GEN = '<!-- Generated by tools/build_docs.py from data/*.yaml. Edit the data, not this file. -->\n\n'

NEGATIVE = (
    'No extra or duplicated characters; exactly the characters listed. No text, captions, '
    'logos, watermarks or UI unless specified. No malformed hands, extra fingers or fused '
    'limbs. No floating feet, foot sliding or ground penetration. No costume, weapon or '
    'damage changes from the descriptions. No morphing faces. No random camera shake, '
    'spinning or zooming beyond the stated move. No teleporting between positions. No '
    'motion blur that hides a silhouette. No bloom that washes out faces or costume detail. '
    'No real-world brand names or copyrighted music.'
)


def esc(text):
    return str(text).replace('|', '\\|').replace('\n', ' ').strip()


def dlg_text(shot, bible):
    out = []
    for d in shot.get('dialogue') or []:
        cid = C.speaker_id(d['who'], bible)
        cue = bible['characters'][cid].get('cue', d['who']) if cid else d['who']
        note = ' (%s)' % d['note'] if d.get('note') else ''
        out.append('%s%s: "%s"' % (cue, note, d['line']))
    return out


def state_line(cid, st, bible):
    c = bible['characters'].get(cid, {})
    return ('**%s** - damage %s/3, power %s%%; %s Equipment: %s. Injury: %s. Emotion: %s'
            % (c.get('name', cid), st.get('damage', '?'), st.get('power', '?'),
               st.get('look', ''), st.get('equipment', '-'), st.get('injury', '-'),
               st.get('emotion', '-')))


def storyboard(seqs, states, bible, locs):
    out_dir = os.path.join(C.DOCS, 'C_storyboard')
    os.makedirs(out_dir, exist_ok=True)
    index = [GEN, '# Deliverable C: Detailed Storyboard\n\n',
             'Every shot of the film with the 13 fields required by the brief (shot number, '
             'duration, camera position, lens, movement, framing, action, lighting, '
             'environmental motion, visual effects, sound, dialogue, transition), plus '
             'timecodes and the continuity state of every principal in the shot.\n\n',
             'Timecodes: **REC** is the film timecode (picture start 01:00:00:00); **SEQ** is '
             'the position inside the sequence (mm:ss:ff). 24 fps. Frame ranges are inclusive '
             'start, exclusive end.\n\n',
             'Sequence 1 has rendered storyboard frames from the prototype (see '
             '[`../F_prototype.md`](../F_prototype.md) and `output/s01_prototype/storyboard/`).\n\n',
             '| Seq | Title | Shots | Duration | REC in | Music |\n|---|---|---|---|---|---|\n']
    for seq in seqs:
        n = seq['sequence']
        index.append('| [%d](S%02d.md) | %s | %d | %s | %s | %s |\n' % (
            n, n, seq['title'], len(seq['shots']), C.short_tc(seq['frames']),
            C.timecode(C.FILM_START_TC + seq['rec_in']), esc(seq.get('music', ''))))
        lines = [GEN, '# Sequence %d: %s\n\n' % (n, seq['title'])]
        lines.append('**Duration:** %s (%d frames, %d shots) · **REC:** %s - %s · **Music:** %s\n\n' % (
            C.short_tc(seq['frames']), seq['frames'], len(seq['shots']),
            C.timecode(C.FILM_START_TC + seq['rec_in']), C.timecode(C.FILM_START_TC + seq['rec_out']),
            seq.get('music', '')))
        lines.append('**Purpose.** %s\n\n' % seq['purpose'].strip())
        if seq.get('staging'):
            lines.append('**Staging rule.** %s\n\n' % seq['staging'].strip())
        if seq.get('zones'):
            lines.append('**Zones.**\n\n')
            for z, desc in seq['zones'].items():
                lines.append('- **%s**: %s\n' % (z, desc))
            lines.append('\n')
        lines.append('**Shot index**\n\n| Shot | Title | Dur | SEQ in | Location | Characters |\n|---|---|---|---|---|---|\n')
        for shot in seq['shots']:
            lines.append('| [%s](#%s) | %s | %.1f s | %s | %s | %s |\n' % (
                shot['id'], shot['id'].lower(), esc(shot['title']), shot['dur'],
                C.short_tc(shot['seq_in']), shot['location'],
                ', '.join(shot.get('characters') or []) or '-'))
        lines.append('\n---\n\n')
        for shot in seq['shots']:
            st = states[shot['id']]
            lines.append('### %s\n\n' % shot['id'])
            lines.append('**%s** · Scene %s · %s\n\n' % (esc(shot['title']), shot['scene'], shot['location']))
            lines.append('| # | Field | Specification |\n|---|---|---|\n')
            dl = dlg_text(shot, bible)
            rows = [
                ('1', 'Shot number', '%s (scene %s%s)' % (shot['id'], shot['scene'],
                                                          ', zone ' + shot['zone'] if shot.get('zone') else '')),
                ('2', 'Duration', '%.1f s = %d frames · SEQ %s-%s · REC %s-%s' % (
                    shot['dur'], shot['frames'], C.short_tc(shot['seq_in']), C.short_tc(shot['seq_out']),
                    C.timecode(C.FILM_START_TC + shot['rec_in']), C.timecode(C.FILM_START_TC + shot['rec_out']))),
                ('3', 'Camera position', shot['camera']),
                ('4', 'Lens / FOV', shot['lens']),
                ('5', 'Camera movement', shot['movement']),
                ('6', 'Subject framing', shot['framing']),
                ('7', 'Character action', shot['action']),
                ('8', 'Lighting', shot['lighting']),
                ('9', 'Environmental motion', shot['environment']),
                ('10', 'Visual effects', shot['vfx']),
                ('11', 'Sound', shot['sound']),
                ('12', 'Dialogue', '<br>'.join(esc(x) for x in dl) if dl else '-'),
                ('13', 'Transition', shot['transition']),
            ]
            for num, label, val in rows:
                lines.append('| %s | %s | %s |\n' % (num, label, esc(val)))
            principals = [c for c in (shot.get('characters') or []) if c in bible['characters']]
            if principals:
                lines.append('\n**Continuity in shot**\n\n')
                for cid in principals:
                    if cid in st:
                        lines.append('- %s\n' % state_line(cid, st[cid], bible))
            if shot.get('background'):
                lines.append('\n*Also visible in depth (located elsewhere):* %s\n' % ', '.join(shot['background']))
            lines.append('\n')
        with open(os.path.join(out_dir, 'S%02d.md' % n), 'w') as f:
            f.write(''.join(lines))
    with open(os.path.join(out_dir, 'README.md'), 'w') as f:
        f.write(''.join(index))


def continuity_doc(seqs, cont, bible):
    lines = [GEN, '# Deliverable D (part 2): Character Continuity Sheet\n\n',
             'Generated from `data/continuity.yaml`. The state at the **start** of each '
             'sequence, then the shot-level events that change it (events take effect after '
             'the named shot). `tools/qc_shots.py` enforces locations, ordering, exits and '
             'damage against every shot.\n\n',
             'Damage: 0 pristine · 1 scuffed/dusty · 2 visibly damaged · 3 heavily damaged. '
             'Power: usable power or stamina, percent.\n\n']
    for seq in seqs:
        n = seq['sequence']
        base = cont['sequences'].get(n) or {}
        lines.append('## Sequence %d: %s\n\n' % (n, seq['title']))
        lines.append('| Character | Look / costume state | Dmg | Equipment | Injury / fatigue | Location path | Objective | Power | Emotion | Knowledge |\n')
        lines.append('|---|---|---|---|---|---|---|---|---|---|\n')
        for cid, st in base.items():
            name = bible['characters'].get(cid, {}).get('name', cid)
            lines.append('| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n' % (
                name, esc(st.get('look', '')), st.get('damage', ''), esc(st.get('equipment', '')),
                esc(st.get('injury', '')), ' > '.join(st.get('path', [])), esc(st.get('objective', '')),
                st.get('power', ''), esc(st.get('emotion', '')), esc(st.get('knowledge', ''))))
        evs = [(sid, ev) for sid, ev in (cont.get('events') or {}).items() if sid.startswith('S%02d_' % n)]
        if evs:
            lines.append('\n**Events**\n\n')
            for sid, ev in sorted(evs):
                for cid, change in ev.items():
                    lines.append('- after **%s**: %s - %s\n' % (sid, cid, '; '.join('%s = %s' % kv for kv in change.items())))
        lines.append('\n')
    with open(os.path.join(C.DOCS, 'D_continuity_sheet.md'), 'w') as f:
        f.write(''.join(lines))


def prompt_for(seq, shot, st, bible, locs, prev_shot, next_shot):
    chars = bible['characters']
    principals = [c for c in (shot.get('characters') or []) if c in chars]
    others = [c for c in (shot.get('characters') or []) if c not in chars]
    parts = []
    parts.append('INFINITY CRISIS - shot %s "%s". Duration %.1f s (%d frames at 24 fps). '
                 'Aspect 2.39:1 (protect for 16:9 open gate).' % (
                     shot['id'], shot['title'], shot['dur'], shot['frames']))
    parts.append('STYLE: ' + bible['style'].strip())
    if principals or others:
        count = len(principals)
        desc = []
        for cid in principals:
            s = st.get(cid, {})
            dmg = s.get('damage', 0)
            cur = s.get('look', '')
            desc.append('%s CURRENT STATE: %s (damage level %d of 3%s).' % (
                chars[cid]['design'].strip(), cur, dmg,
                '; injury: ' + s['injury'] if s.get('injury') and s.get('injury') != 'None' else ''))
        for cid in others:
            src = bible.get('extras', {}).get(cid) or bible.get('forces', {}).get(cid) or cid
            desc.append('%s: %s' % (cid.replace('_', ' ').title(), src.strip()))
        head = ('CHARACTERS ON SCREEN (exactly %d named character%s%s): ' % (
            count, '' if count == 1 else 's', ', plus the groups listed' if others else ''))
        parts.append(head + ' '.join(desc))
    else:
        parts.append('CHARACTERS ON SCREEN: none (environment only).')
    if shot.get('background'):
        parts.append('ALSO VISIBLE SMALL IN THE DISTANCE: %s.' % ', '.join(
            chars[c]['name'] if c in chars else c for c in shot['background']))
    parts.append('ENVIRONMENT: ' + locs.get(shot['location'], '').strip())
    parts.append('ACTION: ' + shot['action'].strip())
    parts.append('CAMERA: %s Lens: %s Movement: %s Framing: %s' % (
        shot['camera'].strip(), shot['lens'].strip(), shot['movement'].strip(), shot['framing'].strip()))
    parts.append('LIGHTING: ' + shot['lighting'].strip())
    parts.append('ENVIRONMENTAL MOTION: ' + shot['environment'].strip())
    parts.append('EFFECTS: ' + shot['vfx'].strip())
    dl = dlg_text(shot, bible)
    parts.append('SOUND DIRECTION: ' + shot['sound'].strip())
    if dl:
        parts.append('DIALOGUE (for lip-sync/performance; do not render as text): ' + ' '.join(dl))
    cont = []
    if prev_shot:
        cont.append('Previous shot %s ends: %s' % (prev_shot['id'], prev_shot['action'].strip()[:220]))
    if next_shot:
        cont.append('Next shot %s begins: %s' % (next_shot['id'], next_shot['action'].strip()[:160]))
    cont.append('Transition out: %s' % shot['transition'].strip())
    parts.append('CONTINUITY: ' + ' '.join(cont))
    parts.append('NEGATIVE: ' + NEGATIVE)
    return '\n'.join(parts)


def prompts(seqs, states, bible, locs):
    out_dir = os.path.join(C.DOCS, 'G_video_prompts')
    os.makedirs(out_dir, exist_ok=True)
    os.makedirs(os.path.join(C.OUTPUT, 'edit'), exist_ok=True)
    flat = [(seq, shot) for seq in seqs for shot in seq['shots']]
    jsonl = []
    per_seq = {}
    for k, (seq, shot) in enumerate(flat):
        prev_shot = flat[k - 1][1] if k > 0 and flat[k - 1][0] is seq else None
        next_shot = flat[k + 1][1] if k + 1 < len(flat) and flat[k + 1][0] is seq else None
        text = prompt_for(seq, shot, states[shot['id']], bible, locs, prev_shot, next_shot)
        jsonl.append({'shot': shot['id'], 'sequence': seq['sequence'], 'duration_s': shot['dur'],
                      'frames': shot['frames'], 'aspect': '2.39:1', 'fps': C.FPS, 'prompt': text})
        per_seq.setdefault(seq['sequence'], []).append((shot, text))
    with open(os.path.join(C.OUTPUT, 'edit', 'prompts.jsonl'), 'w') as f:
        for row in jsonl:
            f.write(json.dumps(row, ensure_ascii=False) + '\n')
    idx = [GEN, '# Deliverable G: Video-Generation Prompts\n\n',
           'One self-contained prompt per shot (%d prompts). Each prompt restates the style, the '
           'full design of every character on screen with their **current** damage state, the '
           'environment, action, camera, lighting, effects, sound direction, dialogue, '
           'continuity with the neighbouring shots, and negative constraints. No prompt relies '
           'on a model remembering an earlier clip.\n\n' % len(jsonl),
           'Machine-readable copy: [`output/edit/prompts.jsonl`](../../output/edit/prompts.jsonl).\n\n',
           '## How to use\n\n',
           '1. Generate each shot at its exact duration (or the model\'s nearest supported length, '
           'then trim to the frame count in the prompt header). Generate 3-4 takes per shot.\n',
           '2. Lock a reference image per character from the turnaround sheets (Deliverable D) and '
           'pass it as an image/character reference wherever the model supports it; the text '
           'design block is the fallback, never the only control.\n',
           '3. For shots longer than the model\'s limit, split at a motivated point (a cut on '
           'action or a camera move) and generate the second half from the last frame of the first '
           '(image-to-video) with the same prompt.\n',
           '4. Do not ask the model for dialogue audio or music; sound is built in post (Deliverable H).\n',
           '5. Review every take against the QC checklist (Deliverable I) before it goes into the cut.\n\n',
           '**Rights note.** These characters belong to Marvel/Disney and DC/Warner Bros. '
           'Discovery. Many hosted video models refuse named copyrighted characters; this '
           'package is a fan-production concept and any public release needs licensing.\n\n',
           '| Sequence | Prompts |\n|---|---|\n']
    for seq in seqs:
        n = seq['sequence']
        idx.append('| [S%02d %s](S%02d.md) | %d |\n' % (n, seq['title'], n, len(per_seq[n])))
        lines = [GEN, '# Video prompts: Sequence %d, %s\n\n' % (n, seq['title'])]
        for shot, text in per_seq[n]:
            lines.append('## %s: %s\n\n```text\n%s\n```\n\n' % (shot['id'], shot['title'], text))
        with open(os.path.join(out_dir, 'S%02d.md' % n), 'w') as f:
            f.write(''.join(lines))
    with open(os.path.join(out_dir, 'README.md'), 'w') as f:
        f.write(''.join(idx))


def edl(seqs, total):
    d = os.path.join(C.OUTPUT, 'edit')
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, 'edl.csv'), 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['event', 'shot', 'sequence', 'scene', 'title', 'duration_s', 'frames',
                    'rec_in', 'rec_out', 'seq_in', 'location', 'characters', 'transition_out'])
        for k, (seq, shot) in enumerate((s, x) for s in seqs for x in s['shots']):
            w.writerow([k + 1, shot['id'], seq['sequence'], shot['scene'], shot['title'], shot['dur'],
                        shot['frames'], C.timecode(C.FILM_START_TC + shot['rec_in']),
                        C.timecode(C.FILM_START_TC + shot['rec_out']), C.short_tc(shot['seq_in']),
                        shot['location'], ' '.join(shot.get('characters') or []),
                        shot['transition'].strip()])
    # CMX3600: each shot is a clip named after its shot ID, source TC 00:00:00:00 + length
    lines = ['TITLE: INFINITY CRISIS', 'FCM: NON-DROP FRAME', '']
    for k, (seq, shot) in enumerate((s, x) for s in seqs for x in s['shots']):
        reel = shot['id'].replace('_', '')[:8]
        lines.append('%03d  %-8s V     C        %s %s %s %s' % (
            k + 1, reel, C.timecode(0), C.timecode(shot['frames']),
            C.timecode(C.FILM_START_TC + shot['rec_in']), C.timecode(C.FILM_START_TC + shot['rec_out'])))
        lines.append('* FROM CLIP NAME: %s.mov' % shot['id'])
        lines.append('')
    with open(os.path.join(d, 'INFINITY_CRISIS.edl'), 'w') as f:
        f.write('\n'.join(lines))
    rt = ['# Runtime\n\n', '| Seq | Title | Shots | Duration | Avg shot | REC in | REC out |\n|---|---|---|---|---|---|---|\n']
    for seq in seqs:
        rt.append('| %d | %s | %d | %s | %.2f s | %s | %s |\n' % (
            seq['sequence'], seq['title'], len(seq['shots']), C.short_tc(seq['frames']),
            seq['frames'] / C.FPS / len(seq['shots']), C.timecode(C.FILM_START_TC + seq['rec_in']),
            C.timecode(C.FILM_START_TC + seq['rec_out'])))
    n = sum(len(s['shots']) for s in seqs)
    rt.append('| | **Total** | **%d** | **%s** | %.2f s | 01:00:00:00 | %s |\n' % (
        n, C.short_tc(total), total / C.FPS / n, C.timecode(C.FILM_START_TC + total)))
    with open(os.path.join(d, 'runtime.md'), 'w') as f:
        f.write(''.join(rt))
    return ''.join(rt)


def main():
    seqs = C.load_sequences()
    bible = C.load_bible()
    cont = C.load_continuity()
    locs = C.load_locations()
    total = C.timeline(seqs)
    states = {shot['id']: st for _, shot, st in C.shot_states(seqs, cont)}
    storyboard(seqs, states, bible, locs)
    continuity_doc(seqs, cont, bible)
    prompts(seqs, states, bible, locs)
    print(edl(seqs, total))


if __name__ == '__main__':
    main()
