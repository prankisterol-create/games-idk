"""Build every Skibidi Showdown model with Blender.

Run with Blender:
    blender -b -P blender/build_models.py -- [--only SkibidiToilet,CameraHead] [--no-render]
or with the bpy module (pip install bpy):
    python blender/build_models.py [--only ...] [--no-render]

Writes:
    blender/models/<Name>.blend          editable Blender scene (camera + lights set up)
    assets/models/<Name>.fbx / .glb      meshes for Roblox Studio's 3D Importer
    src/shared/Blueprints/<Name>.luau    Part version the game builds when no meshes are imported
    src/shared/Palette.luau              colours/materials (from palette.json)
    assets/renders/*.png                 previews: mesh, in-game Part version, poster
"""

import argparse
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import bpy  # noqa: E402
from mathutils import Vector  # noqa: E402

import lib  # noqa: E402
import models  # noqa: E402

ROOT = os.path.dirname(HERE)
BLEND_DIR = os.path.join(HERE, "models")
MESH_DIR = os.path.join(ROOT, "assets", "models")
RENDER_DIR = os.path.join(ROOT, "assets", "renders")
BLUEPRINT_DIR = os.path.join(ROOT, "src", "shared", "Blueprints")


def parse_args():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else sys.argv[1:]
    p = argparse.ArgumentParser()
    p.add_argument("--only", default="", help="comma separated model names")
    p.add_argument("--no-render", action="store_true")
    p.add_argument("--no-poster", action="store_true")
    p.add_argument("--samples", type=int, default=48)
    p.add_argument("--res", type=int, default=900)
    return p.parse_args(argv)


def build_model(name, spec):
    m = lib.Model(name, marker_up=spec.get("up", 4.0), marker_front=spec.get("front", 2.0))
    spec["build"](m)
    m.markers()
    return m


def export_all(name, m):
    data = lib.blueprint_data(m)
    lib.write_blueprint_luau(data, os.path.join(BLUEPRINT_DIR, name + ".luau"),
                             f"blender/models/{name}.blend")
    lib.export_meshes(m, os.path.join(MESH_DIR, name + ".fbx"),
                      os.path.join(MESH_DIR, name + ".glb"))
    return data


def preview_scene(m, args):
    scene = bpy.context.scene
    lib.setup_render(scene, (args.res, args.res), args.samples)
    mn, mx = lib.model_bounds(m.parts)
    center = (mn + mx) / 2
    radius = (mx - mn).length / 2
    lib.add_floor()
    lib.studio_lights(center, radius)
    lib.frame_camera(center, radius)


def render_previews(name, m, data, args):
    lib.render(os.path.join(RENDER_DIR, name + ".png"))
    # Same framing, Part version only.
    m.collection.hide_render = True
    col = lib.build_from_blueprint(data)
    lib.render(os.path.join(RENDER_DIR, name + "_parts.png"))
    m.collection.hide_render = False
    # Keep the Part preview in the .blend, hidden, for reference.
    col.hide_render = True
    col.hide_viewport = True


def write_index():
    names = sorted(f[:-5] for f in os.listdir(BLUEPRINT_DIR)
                   if f.endswith(".luau") and f != "init.luau")
    lines = ["-- AUTO-GENERATED by blender/build_models.py: every blueprint by name.", "return {"]
    lines += [f"\t{n} = require(script.{n})," for n in names]
    lines.append("}")
    with open(os.path.join(BLUEPRINT_DIR, "init.luau"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


def place(m, loc, yaw=0.0, scale=1.0):
    m.root.location = loc
    m.root.rotation_euler = (0, 0, math.radians(yaw))
    m.root.scale = (scale, scale, scale)


def poster(args):
    lib.reset_scene()
    scene = bpy.context.scene
    lib.setup_render(scene, (1600, 900), args.samples)
    heads = {"Cameraman": "CameraHead", "Speakerman": "SpeakerHead", "TVMan": "TVHead"}
    everything = []
    agents = [("Speakerman", (-9.0, 2.5, 0), 55), ("Cameraman", (-6.0, -1.5, 0), 48),
              ("TVMan", (-11.5, -2.5, 0), 42)]
    for cls, loc, yaw in agents:
        suit = lib.Model(cls + "Suit", mat_overrides=models.SUITS[cls])
        models.agent_suit(suit)
        place(suit, loc, yaw)
        head = lib.Model(cls + "Head")
        models.MODELS[heads[cls]]["build"](head)
        head.root.parent = suit.root
        head.root.location = (0, 0, 4)
        everything += suit.parts + head.parts
    toilets = [("SkibidiToilet", (2.5, -1.0, 0), -40, 1.0), ("SpeedyToilet", (5.5, -3.2, 0), -30, 0.85),
               ("LaserToilet", (6.0, 2.0, 0), -50, 1.0), ("TankToilet", (10.0, -0.5, 0), -45, 1.45),
               ("GToilet", (6.0, 10.0, 0), -35, 2.6)]
    for name, loc, yaw, s in toilets:
        t = lib.Model(name + "_P")
        models.MODELS[name]["build"](t)
        place(t, loc, yaw, s)
        everything += t.parts
    portal = lib.Model("Portal_P")
    models.toilet_portal(portal)
    place(portal, (16, 18, 0), -30, 1.4)
    lib.add_floor(size=200)
    mn, mx = lib.model_bounds(everything)
    center = (mn + mx) / 2 + Vector((0, 0, -1.0))
    radius = (mx - mn).length / 2
    lib.studio_lights(center, radius * 0.6)
    lib.frame_camera(center, radius * 0.62, direction=(0.0, -1.0, 0.22), lens=40, aspect=16 / 9)
    lib.render(os.path.join(RENDER_DIR, "poster.png"))
    bpy.ops.wm.save_as_mainfile(filepath=os.path.join(BLEND_DIR, "Poster.blend"), compress=True)


def main():
    args = parse_args()
    for d in (BLEND_DIR, MESH_DIR, RENDER_DIR, BLUEPRINT_DIR):
        os.makedirs(d, exist_ok=True)
    lib.write_palette_luau(os.path.join(ROOT, "src", "shared", "Palette.luau"))
    only = [n for n in args.only.split(",") if n]
    for name, spec in models.MODELS.items():
        if only and name not in only:
            continue
        print(f"== {name}")
        lib.reset_scene()
        m = build_model(name, spec)
        data = export_all(name, m)
        preview_scene(m, args)
        if not args.no_render:
            render_previews(name, m, data, args)
        bpy.ops.wm.save_as_mainfile(filepath=os.path.join(BLEND_DIR, name + ".blend"),
                                    compress=True)
        tris = sum(len(o.data.polygons) for o in m.parts if o.type == "MESH")
        print(f"   {len(data['parts'])} parts, {len(data['joints'])} joints, {tris} faces")
    write_index()
    if not args.no_render and not args.no_poster and not only:
        print("== Poster")
        poster(args)


if __name__ == "__main__":
    main()
